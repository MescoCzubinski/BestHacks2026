// Renders nginx.conf from public-routes.json, the single allowlist shared with the Vite dev proxy.
// node ingress/render-nginx.mjs          writes ingress/nginx.conf
// node ingress/render-nginx.mjs --check  fails when the committed file is out of date
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const routes = JSON.parse(
  readFileSync(join(here, "public-routes.json"), "utf-8"),
);
const target = join(here, "nginx.conf");

const escape = (path) => path.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const prefixes = routes.prefix.map(escape).join("|");

const proxy = `    proxy_pass http://backend;
    proxy_set_header Host $host;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto $scheme;`;

const exact = routes.exact
  .map((path) => `  location = ${path} {\n${proxy}\n  }\n`)
  .join("\n");

const conf = `# Generated by ingress/render-nginx.mjs from public-routes.json. Do not edit by hand.
# The only public entry point: / goes to the frontend, an allowlist of /api routes to the backend.

upstream frontend {
  server frontend:3000;
}

upstream backend {
  server backend:8000;
}

server {
  listen 80;

  location ~ ^(${prefixes})(/|$) {
${proxy}
  }

${exact}
  location /api/ {
    return 404;
  }

  location / {
    proxy_pass http://frontend;
    proxy_set_header Host $host;
  }
}
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf-8");
  } catch {}
  if (current !== conf) {
    console.error(
      "ingress/nginx.conf is out of date: run node ingress/render-nginx.mjs",
    );
    process.exit(1);
  }
} else {
  writeFileSync(target, conf);
}
